"""Generate a strategy scaffold: the declaration filled in, the decision left to write.

Design: ``docs/fullspec/author_check_and_scaffold_design.md`` section 3.5. One JSON input (the
strategy id, the class name, the series, the timeframes, ``min_history``, the policies, the four
capabilities, the parameters, the twelve ``StrategyProfile`` values, and the display name and
description the registration row needs) becomes four files:

- the strategy module, whose declaration is the input as given, whose ``decision_contract`` is
  always ``DECISION_INTENT``, and whose ``analyze`` reads the inputs and every declared series
  through the ``StrategyBase`` helpers and then returns ``HOLD("scaffold")`` at the one place
  marked for the author;
- the test module, with the declaration test, the registration-file test, and the decision
  test's empty place, keyed by ``series_key_of``;
- the registration SQL, generated by the fact module's ``registration_sql`` and written under
  ``init-scripts/signal-service/<date>/``;
- one ``\\ir`` line appended to ``init-scripts/06-init-signal-registry.sql``.

A scaffold straight out of this tool passes pre-deployment stages 1 to 5 and 7 without a
decision, so what the author fills in is the decision alone. No legacy ``TradingSignal``
scaffold and no policy scaffold are generated. Existing files are never overwritten: the tool
refuses before writing anything.

This module writes files, so it is not part of the fact module.
"""

