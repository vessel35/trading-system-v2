def _read_timeframe(descriptor: Mapping[str, Any]) -> str:
    """The extra argument a series declared on its own timeframe is read with."""
    declared = descriptor.get("timeframe")
    if isinstance(declared, str) and declared != "strategy":
        return f", {_literal(declared)}"
    return ""


def _field_arguments(spec: Mapping[str, Any]) -> str:
    parts = [f"type={_literal(spec['type'])}"]
    if "default" in spec:
        parts.append(f"default={_literal(spec['default'])}")
