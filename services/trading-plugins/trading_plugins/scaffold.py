def _next_registration_name(directory: Path, strategy_id: str) -> str:
    existing = sorted(directory.glob("[0-9][0-9]-*.sql")) if directory.exists() else []
    numbers = [int(path.name[:2]) for path in existing]
    return f"{(max(numbers) + 1) if numbers else 1:02d}-register-{strategy_id}.sql"


_SERVICE_CONFIG: Final = Path(__file__).resolve().parents[1] / "pyproject.toml"


def _format(paths: Sequence[Path]) -> bool:
    """Run ruff format over the generated modules so stage 7's format check holds.

    The plugins service's own configuration is named explicitly, so the result does not
    depend on the directory the tool was started from.
    """
    try:
        completed = subprocess.run(  # noqa: S603 - fixed arguments, generated paths
            [
                sys.executable,
                "-m",
                "ruff",
                "format",
                "--config",
                str(_SERVICE_CONFIG),
                *map(str, paths),
            ],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return False
    return completed.returncode == 0


def scaffold(
    spec: ScaffoldSpec,
    root: Path = REPOSITORY_ROOT,
    *,
    statement_for: StatementBuilder | None = None,
) -> ScaffoldResult:
    """Write the four artifacts under ``root``; refuse if any of them already exists.

    ``statement_for`` builds the registration statement; the default asks the fact module,
    which discovers the module just written in the deployed package. A test working under
    another root passes its own builder, because discovery looks only at the fixed package.
    """
    strategy_module = root / _STRATEGIES / f"{spec.module_name}.py"
    test_module = root / _TESTS / f"test_{spec.module_name}.py"
    registration_directory = root / _REGISTRATIONS / spec.registration_date
    registration_sql = registration_directory / _next_registration_name(
        registration_directory, spec.strategy_id
    )
    init_script = root / _INIT_SCRIPT
    relative_sql = registration_sql.relative_to(root / "init-scripts").as_posix()
    init_line = f"\\ir {relative_sql}"
    existing = [path for path in (strategy_module, test_module, registration_sql) if path.exists()]
    if existing:
        raise FileExistsError("refusing to overwrite: " + ", ".join(str(path) for path in existing))
    if not init_script.exists():
        raise FileNotFoundError(f"init script is missing: {init_script}")
    if init_line in init_script.read_text().splitlines():
        raise FileExistsError(f"init script already includes {relative_sql}")
    for directory in (strategy_module.parent, test_module.parent, registration_directory):
        directory.mkdir(parents=True, exist_ok=True)

    original_init = init_script.read_text()
    written: list[Path] = []
    try:
        strategy_module.write_text(render_strategy_module(spec))
        written.append(strategy_module)
        builder = _default_statement if statement_for is None else statement_for
        statement = builder(spec.strategy_id, spec.display_name, spec.description)
        registration_sql.write_text(render_registration_file(statement))
        written.append(registration_sql)
        registration_relative = registration_sql.relative_to(root).as_posix()
        test_module.write_text(render_test_module(spec, registration_relative))
        written.append(test_module)
        init_script.write_text(original_init.rstrip("\n") + "\n" + init_line + "\n")
    except BaseException:
        # Leave nothing behind: a half-written scaffold would block the retry through the
        # overwrite guard and sit in the deployed package as a broken module.
        for path in written:
            path.unlink(missing_ok=True)
        init_script.write_text(original_init)
        raise
    formatted = _format((strategy_module, test_module))
    return ScaffoldResult(
        strategy_module, test_module, registration_sql, init_script, init_line, formatted
    )


_USAGE: Final = "usage: python -m trading_plugins.scaffold <input.json>"


def main(argv: Sequence[str] | None = None) -> int:
    """Generate the scaffold from one JSON file; print where the files went, or the error."""
    arguments = list(sys.argv[1:] if argv is None else argv)
    if len(arguments) != 1:
        print(json.dumps({"error": _USAGE}))
        return 1
    try:
        loaded = json.loads(Path(arguments[0]).read_text())
        if not isinstance(loaded, dict):
            raise ValueError("input must be a JSON object")
        result = scaffold(ScaffoldSpec.from_json(loaded))
    except (Exception, SystemExit) as error:  # noqa: BLE001 - the boundary reports, never raises
        print(json.dumps({"error": f"{type(error).__name__}: {error}"}))
        return 1
    print(json.dumps(result.as_json(), sort_keys=True))
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through main() in tests
    sys.exit(main())
