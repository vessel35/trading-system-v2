@dataclass(frozen=True)
class ScaffoldSpec:
    """The validated scaffold input."""

    strategy_id: str
    class_name: str
    display_name: str
    description: str
    series: tuple[Mapping[str, Any], ...]
    supported_timeframes: tuple[str, ...]
    min_history: int
    supported_modes: tuple[str, ...]
    default_mode: str
    default_settings: Mapping[str, Mapping[str, Any]]
    capabilities: Mapping[str, bool]
    parameters: Mapping[str, Mapping[str, Any]]
    profile: Mapping[str, Any]
    registration_date: str

    @property
    def module_name(self) -> str:
        return self.strategy_id.replace("-", "_")

    @classmethod
    def from_json(cls, data: Mapping[str, Any]) -> ScaffoldSpec:
        """Validate the input the way the generated declaration will be validated."""
        unknown = sorted(set(data) - _INPUT_KEYS)
        if unknown:
            raise ValueError(f"unknown input keys: {unknown}")
        missing = sorted(_INPUT_KEYS - {"registration_date"} - set(data))
        if missing:
            raise ValueError(f"missing input keys: {missing}")
        strategy_id = _text(data, "strategy_id")
        if not is_plugin_identifier(strategy_id):
            raise ValueError(
                f"strategy_id must be kebab-case ({PLUGIN_IDENTIFIER_PATTERN.pattern}): "
                f"{strategy_id!r}"
            )
        display_name = _docstring_safe(_text(data, "display_name"), "display_name")
        if len(display_name) > 60 or "\n" in display_name:
            raise ValueError("display_name must be one line of at most 60 characters")
        description = _docstring_safe(_text(data, "description"), "description")
        class_name = _text(data, "class_name")
        if (
            not class_name.isidentifier()
            or keyword.iskeyword(class_name)
            or not class_name[0].isupper()
        ):
            raise ValueError(f"class_name must be a capitalized identifier: {class_name!r}")
        series = data["series"]
        if not isinstance(series, list) or not all(
            isinstance(item, dict)
            and isinstance(item.get("name"), str)
            and item["name"]
            and isinstance(item.get("params"), dict)
            and set(item) <= {"name", "params", "timeframe"}
            for item in series
        ):
            raise ValueError("series must be a list of {name, params[, timeframe]} objects")
        timeframes = data["supported_timeframes"]
        if (
            not isinstance(timeframes, list)
            or not timeframes
            or not all(isinstance(item, str) and item for item in timeframes)
        ):
            raise ValueError("supported_timeframes must be a non-empty list of strings")
        min_history = data["min_history"]
        if isinstance(min_history, bool) or not isinstance(min_history, int) or min_history < 1:
            raise ValueError("min_history must be an integer of at least 1")
        money = data["money_management"]
        if not isinstance(money, dict) or set(money) - {"supported", "default", "default_settings"}:
            raise ValueError("money_management must hold supported, default, and default_settings")
        supported = money.get("supported")
        default = money.get("default")
        if (
            not isinstance(supported, list)
            or not supported
            or not all(isinstance(item, str) and is_plugin_identifier(item) for item in supported)
        ):
            raise ValueError("money_management.supported must be a non-empty list of modes")
        if not isinstance(default, str) or default not in supported:
            raise ValueError("money_management.default must be one of the supported modes")
        default_settings = money.get("default_settings", {})
        if not isinstance(default_settings, dict) or not all(
            isinstance(value, dict) for value in default_settings.values()
        ):
            raise ValueError(
                "money_management.default_settings must map a mode to a settings object"
            )
        capabilities = data["capabilities"]
        if (
            not isinstance(capabilities, dict)
            or set(capabilities) != set(_CAPABILITIES)
            or not all(isinstance(value, bool) for value in capabilities.values())
        ):
            raise ValueError(f"capabilities must hold exactly {list(_CAPABILITIES)} as booleans")
        parameters = data["parameters"]
        if not isinstance(parameters, dict):
            raise ValueError("parameters must be an object of name to field")
        for name, spec in parameters.items():
            if not isinstance(name, str) or not name.isidentifier():
                raise ValueError(f"parameter name must be an identifier: {name!r}")
            if name in MONEY_MANAGEMENT_OWNED_PARAMETERS:
                raise ValueError(f"parameter {name!r} belongs to the money-management policy")
            if not isinstance(spec, dict) or "type" not in spec or set(spec) - _PARAMETER_KEYS:
                raise ValueError(
                    f"parameter {name!r} must hold type and optionally default, range, required"
                )
        profile = data["profile"]
        if not isinstance(profile, dict) or set(profile) != set(_PROFILE_FIELDS):
            raise ValueError(f"profile must hold exactly the twelve fields {list(_PROFILE_FIELDS)}")
        date = data.get("registration_date", datetime.now(UTC).strftime("%Y%m%d"))
        if not isinstance(date, str) or len(date) != 8 or not date.isdigit():
            raise ValueError("registration_date must be YYYYMMDD")
        spec = cls(
            strategy_id=strategy_id,
            class_name=class_name,
            display_name=display_name,
            description=description,
            series=tuple(dict(item) for item in series),
            supported_timeframes=tuple(timeframes),
            min_history=min_history,
            supported_modes=tuple(supported),
            default_mode=default,
            default_settings={str(k): dict(v) for k, v in default_settings.items()},
            capabilities={name: bool(capabilities[name]) for name in _CAPABILITIES},
            parameters={str(k): dict(v) for k, v in parameters.items()},
            profile=dict(profile),
            registration_date=date,
        )
        spec.build_profile()
        spec.build_money_management()
        spec.build_parameter_schema()
        spec.validate_against_the_platform()
        return spec

    def validate_against_the_platform(
        self, policies: Mapping[str, type[MoneyManagementBase]] | None = None
    ) -> None:
        """Refuse what pre-deployment stages 2 and 3 would refuse, before any file is written.

        Every timeframe must be well formed, every series must resolve in the registries for
        every supported timeframe, every mode must be deployed with its declared settings
        accepted, and a policy that requires signal exits needs a strategy that emits them.
        """
        for timeframe in self.supported_timeframes:
            try:
                series_key_of("probe", {}, timeframe)
            except ValueError as error:
                raise ValueError(
                    f"supported timeframe {timeframe!r} is malformed: {error}"
                ) from error
        for descriptor in self.series:
            for timeframe in self.supported_timeframes:
                try:
                    series_specs_from_descriptors(
                        [descriptor],
                        DEFAULT_REGISTRY,
                        DEFAULT_PATTERN_REGISTRY,
                        execution_timeframe=timeframe,
                    )
                except (Exception, SystemExit) as error:  # noqa: BLE001 - reported as the reason
                    raise ValueError(
                        f"series {descriptor} does not resolve at {timeframe}: "
                        f"{type(error).__name__}: {error}"
                    ) from error
        deployed = discover_money_management()[0] if policies is None else policies
        for mode in self.supported_modes:
            policy_class = deployed.get(mode)
            if policy_class is None:
                raise ValueError(f"money-management mode {mode!r} is not deployed")
            settings = {"mode": mode, **dict(self.default_settings.get(mode, {}))}
            try:
                policy = MoneyManagementFactory.create(settings, deployed)
            except (Exception, SystemExit) as error:  # noqa: BLE001
                raise ValueError(
                    f"default_settings for {mode!r} are refused: {type(error).__name__}: {error}"
                ) from error
            if policy.requires_signal_exit and not self.capabilities["supports_signal_exit"]:
                raise ValueError(
                    f"mode {mode!r} requires signal exits, but supports_signal_exit is false"
                )

    def build_profile(self) -> StrategyProfile:
        """The profile the generated module declares; building it validates the input."""
        values = dict(self.profile)
        values["expected_win_rate"] = tuple(values["expected_win_rate"])
        values["expected_payoff"] = tuple(values["expected_payoff"])
        return StrategyProfile(**values)

    def build_money_management(self) -> MoneyManagementSupport:
        return MoneyManagementSupport(
            supported=self.supported_modes,
            default=self.default_mode,
            default_settings=self.default_settings,
            **self.capabilities,
        )

    def build_parameter_schema(self) -> ParameterSchema:
        fields: dict[str, FieldSpec] = {}
        for name, spec in self.parameters.items():
            keywords: dict[str, Any] = {"type": spec["type"]}
            if "default" in spec:
                keywords["default"] = spec["default"]
            if "range" in spec:
                keywords["range"] = tuple(spec["range"])
            if "required" in spec:
                keywords["required"] = bool(spec["required"])
            fields[name] = FieldSpec(**keywords)
        return ParameterSchema(fields=fields)


def _text(data: Mapping[str, Any], key: str) -> str:
    value = data.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{key} must be a non-empty string")
    return value


def _docstring_safe(value: str, key: str) -> str:
    """Refuse text that would end or escape the docstring it is written into."""
    if '"""' in value or "\\" in value:
        raise ValueError(f"{key} must not contain a docstring delimiter or a backslash")
    return value


